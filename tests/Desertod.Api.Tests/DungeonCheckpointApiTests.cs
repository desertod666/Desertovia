    private readonly Players players = new(factory);
    private IDbContextFactory<DesertodDbContext> Contexts => factory.Services.GetRequiredService<IDbContextFactory<DesertodDbContext>>();

    private static Task Tick(DungeonWorker worker, LiveDungeon live, CancellationToken ct = default) =>
        (Task)typeof(DungeonWorker).GetMethod("TickDurableAsync", BindingFlags.Instance | BindingFlags.NonPublic)!
            .Invoke(worker, [live, .1, ct])!;

    private async Task<(GameService Game, DungeonRuntime Runtime, LiveDungeon Live)> Setup(
        DungeonRuntime? runtime = null, bool exiting = false)
    {
        var founded = await players.FoundVillageAsync("Durable expedition");
        var resident = await players.JoinAsync(founded);
        await using var db = await Contexts.CreateDbContextAsync();
        var village = await db.Villages.SingleAsync(v => v.Slug == founded.Slug);
        var citizen = await db.Citizens.SingleAsync(c => c.Id == resident.Id);
        var now = factory.Clock.GetUtcNow();
        var run = DungeonRules.Open(village, DungeonCatalog.DeadLands, "Tsar", 186, now);
        DungeonRules.Join(run, village, citizen, HeroClass.Brawler, now);
        DungeonRules.March(run, village, [citizen], now);
        DungeonRules.Start(run, now);
        var fighters = new[]
        {
            new DungeonFighter(village.OwnerAccountId, village.OwnerAccountId, "Tsar", HeroClass.Voivode, 1000, 1, 0, null, false),
            new DungeonFighter(citizen.Id, citizen.AccountId, citizen.Name, HeroClass.Brawler, 1000, 1, 0, null, false),
        };
        var heroes = fighters.Select(f => new DungeonRunHeroDto(f.Id, f.Class == HeroClass.Voivode ? null : f.Id,
            f.Name, f.Class, null, f.Health)).ToArray();
        var simulation = new DungeonSimulation(DungeonCatalog.Get(run.DungeonId), fighters);
        simulation.MoveTo(citizen.Id, 4.17, 5.23);
        if (exiting)
        {
            simulation.Hero(citizen.Id)!.Loot[ResourceKind.Food] = 3;
            foreach (var fighter in fighters) simulation.WithdrawToHospital(fighter.Id);
        }
        var save = new DungeonSave(0, simulation.Capture(), DungeonRandom.FromSeed(run.Seed).State, heroes, []);
        run.CheckpointJson = save.ToJson();
        db.DungeonRuns.Add(run);
        await db.SaveChangesAsync();
        runtime ??= new DungeonRuntime();
        return (factory.Services.GetRequiredService<GameService>(), runtime, runtime.Start(save.Resume(run, village.Slug)));
    }

    private DungeonWorker Worker(DungeonRuntime runtime) => ActivatorUtilities.CreateInstance<DungeonWorker>(
        factory.Services, runtime, NullLogger<DungeonWorker>.Instance);

    private sealed class Caller(Guid accountId) : HubCallerContext
    {
        public override string ConnectionId => "checkpoint-test";
        public override string? UserIdentifier => accountId.ToString();
        public override ClaimsPrincipal User { get; } = new(new ClaimsIdentity([new Claim(AccountClaims.AccountId, accountId.ToString())], "test"));
        public override IDictionary<object, object?> Items { get; } = new Dictionary<object, object?>();
        public override IFeatureCollection Features { get; } = new FeatureCollection();
        public override CancellationToken ConnectionAborted => default;
        public override void Abort() { }
    }

    private async Task<string> RejectWrites(LiveDungeon live)
    {
        var name = "reject_dungeon_" + live.RunId.ToString("N");
        await using var db = await Contexts.CreateDbContextAsync();
        // Both SQL identifiers and literals are generated here from a Guid, never from user input.
#pragma warning disable EF1002
        await db.Database.ExecuteSqlRawAsync($"ALTER TABLE \"DungeonRuns\" ADD CONSTRAINT {name} CHECK (\"Id\" <> '{live.RunId}'::uuid OR (\"CheckpointJson\"->>'Revision')::bigint = 0)");
#pragma warning restore EF1002
        return name;
    }

    private async Task AllowWrites(string name)
    {
        await using var db = await Contexts.CreateDbContextAsync();
#pragma warning disable EF1002 // Name is generated by RejectWrites from a Guid.
        await db.Database.ExecuteSqlRawAsync($"ALTER TABLE \"DungeonRuns\" DROP CONSTRAINT {name}");
#pragma warning restore EF1002
    }

    [Fact]
    public async Task A_group_viewer_reconnects_to_the_admitted_bodies_and_saved_map_even_before_runtime_restore()
    {
        using var frozen=factory.Clock.Freeze();var s=await Setup();
        var body=s.Live.Simulation.Heroes.Single(h=>!h.IsTsar);
        await players.ArrangeCitizenAsync(body.Id,(c,_)=>c.Stats.Endurance=9);
        var saved=s.Live.Save!;
        var view=Assert.IsType<DungeonRunDto>(await s.Game.GetDungeonRunAsync(s.Live.RunId,body.Fighter.AccountId,default));
        Assert.Equal(saved.Heroes,view.Heroes);Assert.Equal(body.Id,view.MyHeroId);
        Assert.All(view.Heroes,h=>Assert.Equal(1000,h.MaximumHealth));
        Assert.Equal(saved.Fight.Definition.Width,view.Width);Assert.Equal(saved.Fight.Definition.Height,view.Height);
        Assert.Equal(DungeonMapper.EncodeTiles(saved.Fight.Definition),view.Tiles);
        var restored=new DungeonRuntime().Start(Assert.Single(await s.Game.RestoreDungeonsAsync(default),r=>r.RunId==s.Live.RunId));
        Assert.Equal(view.Heroes,restored.Save!.Heroes);Assert.Equal(saved.ToJson(),restored.Save.ToJson());
    }

    [Fact]
    public async Task New_process_recovers_the_committed_fight_and_rejects_a_stale_writer()
    {
        var s = await Setup();
        using var worker = Worker(s.Runtime);
        await Tick(worker, s.Live);
        Assert.Equal(1, s.Live.Save!.Revision);
        Assert.Equal(.1, s.Live.Simulation.Elapsed);
        var starts = await s.Game.RestoreDungeonsAsync(default);
        var resumed = new DungeonRuntime().Start(Assert.Single(starts, r => r.RunId == s.Live.RunId));
        Assert.Equal(s.Live.Save.ToJson(), resumed.Save!.ToJson());
        Assert.Equal(s.Live.LastSnapshot!.Heroes[1].X, DungeonMapper.Snapshot(resumed.RunId, resumed.Simulation, []).Heroes[1].X);
        var stale = resumed.Save with { Fight = resumed.Save.Fight with { Elapsed = 9 } };
        await Assert.ThrowsAsync<GameRuleException>(() => s.Game.SettleDungeonAsync(
            resumed.RunId, resumed.VillageId, [], null, 0, default, stale));
        await using var db = await Contexts.CreateDbContextAsync();
        Assert.Equal(1, DungeonSave.Read((await db.DungeonRuns.SingleAsync(r => r.Id == resumed.RunId)).CheckpointJson!).Revision);
    }

    [Fact]
    public async Task Failed_write_does_not_publish_or_advance_and_is_retryable()
    {
        var s = await Setup();
        using var worker = Worker(s.Runtime);
        var before = s.Live.Save!.ToJson();
        var constraint = await RejectWrites(s.Live);
        try
        {
            await Tick(worker, s.Live);
            Assert.Equal(before, s.Live.Save.ToJson());
            Assert.Null(s.Live.LastSnapshot);
            Assert.Equal(0, s.Live.Simulation.Elapsed);
        }
        finally { await AllowWrites(constraint); }
        await Tick(worker, s.Live);
        Assert.Equal(1, s.Live.Save.Revision);
        Assert.Equal(.1, s.Live.LastSnapshot!.Elapsed);
    }

    [Fact]
    public async Task Final_checkpoint_and_loot_commit_together_and_cannot_be_paid_again_after_restart()
    {
        var s = await Setup(exiting: true);
        using var worker = Worker(s.Runtime);
        await using var db = await Contexts.CreateDbContextAsync();
        var villageBefore = await db.Villages.AsNoTracking().SingleAsync(v => v.Id == s.Live.VillageId);
        var citizenId = s.Live.Simulation.Heroes[1].Id;
        var carriedBefore = (await players.LoadCitizenAsync(citizenId)).Carried(ResourceKind.Food);
        var constraint = await RejectWrites(s.Live);
        try
        {
            await Tick(worker, s.Live);
            Assert.Same(s.Live, s.Runtime.Find(s.Live.RunId));
            Assert.Empty(s.Live.Settled);
            var failed = await db.DungeonRuns.AsNoTracking().SingleAsync(r => r.Id == s.Live.RunId);
            Assert.Equal(DungeonPhase.Running, failed.Phase);
            Assert.All(failed.Heroes, h => Assert.False(h.Settled));
        }
        finally { await AllowWrites(constraint); }
        await Tick(worker, s.Live);
        Assert.Null(s.Runtime.Find(s.Live.RunId));
        var finished = await db.DungeonRuns.AsNoTracking().SingleAsync(r => r.Id == s.Live.RunId);
        Assert.Equal(DungeonPhase.Ended, finished.Phase);
        Assert.All(finished.Heroes, h => Assert.True(h.Settled));
        Assert.Equal(3, Assert.Single(finished.Heroes, h => !h.IsTsar).Loot.Sum(g => g.Amount));
        var villageAfter = await db.Villages.AsNoTracking().SingleAsync(v => v.Id == s.Live.VillageId);
        var foodAfter = villageAfter.Stock(ResourceKind.Food) + (await players.LoadCitizenAsync(citizenId)).Carried(ResourceKind.Food);
        Assert.Equal(villageBefore.Stock(ResourceKind.Food) + carriedBefore + 3, foodAfter);
        Assert.DoesNotContain(await s.Game.RestoreDungeonsAsync(default), r => r.RunId == s.Live.RunId);
        // Simulate the client losing a successful commit acknowledgement and retrying the same result.
        await s.Game.SettleDungeonAsync(s.Live.RunId, s.Live.VillageId, [], DungeonOutcome.Defeat, 0, default, s.Live.Save);
        var next = s.Live.Save! with { Revision = s.Live.Save!.Revision + 1 };
        await Assert.ThrowsAsync<GameRuleException>(() => s.Game.SettleDungeonAsync(s.Live.RunId, s.Live.VillageId,
            [], DungeonOutcome.Defeat, 0, default, next));
        Assert.Equal(foodAfter, (await db.Villages.AsNoTracking().SingleAsync(v => v.Id == s.Live.VillageId)).Stock(ResourceKind.Food)
            + (await players.LoadCitizenAsync(citizenId)).Carried(ResourceKind.Food));
    }

    [Fact]
    public async Task Manual_command_is_acknowledged_only_after_commit_and_cannot_control_another_hero()
    {
        var s = await Setup();
        var hero = s.Live.Simulation.Heroes[0];
        var hub = new DungeonHub(s.Runtime, s.Game) { Context = new Caller(hero.Fighter.AccountId) };
        Assert.False(await hub.MoveTo(s.Live.RunId, s.Live.Simulation.Heroes[1].Id, 5.17, 5.23));
        var constraint = await RejectWrites(s.Live);
        try
        {
            await Assert.ThrowsAsync<DbUpdateException>(() => hub.MoveTo(s.Live.RunId, hero.Id, 5.17, 5.23));
            Assert.Equal(0, s.Live.Save!.Revision);
            Assert.Null(s.Live.Simulation.Hero(hero.Id)!.Destination);
        }
        finally { await AllowWrites(constraint); }
        Assert.True(await hub.MoveTo(s.Live.RunId, hero.Id, 5.17, 5.23));
        Assert.Equal(1, s.Live.Save!.Revision);
        var restored = Assert.Single(await s.Game.RestoreDungeonsAsync(default), r => r.RunId == s.Live.RunId);
        Assert.Equal(s.Live.Simulation.Hero(hero.Id)!.Destination, DungeonSimulation.Restore(restored.Save!.Fight).Hero(hero.Id)!.Destination);
    }

    [Fact]
    public async Task One_blocked_village_does_not_hold_up_another_fight()
    {
        var s = await Setup();
        var other = await Setup(s.Runtime);
        using var worker = Worker(s.Runtime);
        var locks = (VillageLocks)typeof(GameService).GetField("locks", BindingFlags.Instance | BindingFlags.NonPublic)!.GetValue(s.Game)!;
        using var blocked = await locks.AcquireAsync(s.Live.VillageId, default);
        using var cancellation = new CancellationTokenSource();
        var pending = Tick(worker, s.Live, cancellation.Token);
        try
        {
            await Tick(worker, other.Live).WaitAsync(TimeSpan.FromSeconds(5));
            Assert.False(pending.IsCompleted);
            Assert.Equal(0, s.Live.Simulation.Elapsed);
            Assert.Equal(.1, other.Live.LastSnapshot!.Elapsed);
        }
        finally { cancellation.Cancel(); await pending; }
        Assert.Equal(0, s.Live.Save!.Revision);
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public async Task Voluntary_retreat_is_owned_durable_and_cannot_enter_safe_rest_before_reaching_the_exit(bool tsar)
    {
        var s=await Setup();var hero=s.Live.Simulation.Heroes.Single(h=>h.IsTsar==tsar);
        var other=s.Live.Simulation.Heroes.Single(h=>h.IsTsar!=tsar);
        var hub=new DungeonHub(s.Runtime,s.Game){Context=new Caller(hero.Fighter.AccountId)};
        Assert.False(await hub.Retreat(s.Live.RunId,other.Id));
        Assert.True(await hub.Retreat(s.Live.RunId,hero.Id));
        Assert.Equal(1,s.Live.Save!.Revision);Assert.True(s.Live.Simulation.Hero(hero.Id)!.RetreatRequested);
        Assert.True(DungeonMapper.Snapshot(s.Live.RunId,s.Live.Simulation,[]).Heroes.Single(h=>h.Id==hero.Id).Retreating);
        var rejected=await Assert.ThrowsAsync<GameRuleException>(()=>s.Game.SetRestAsync(s.Live.Slug,hero.Fighter.AccountId,new(true),default));
        Assert.Equal("rest.dungeonRequired",rejected.Code);
        using var worker=Worker(s.Runtime);
        for(var i=0;i<20&&s.Live.Simulation.Hero(hero.Id)!.State!=HeroState.Left;i++)
        {
            // The worker normally samples monotonic wall time after its first tick. This
            // manually driven scenario advances explicit .1s steps, even on a fast CI host.
            s.Live.LastTickTimestamp=0;
            await Tick(worker,s.Live);
        }
        Assert.Equal(HeroState.Left,s.Live.Simulation.Hero(hero.Id)!.State);
        await using var db=await Contexts.CreateDbContextAsync();
        var run=await db.DungeonRuns.AsNoTracking().SingleAsync(r=>r.Id==s.Live.RunId);
        Assert.True(run.Heroes.Single(h=>h.AccountId==hero.Fighter.AccountId).Settled);
        Assert.False(run.Heroes.Single(h=>h.AccountId==hero.Fighter.AccountId).KnockedOut);
        await s.Game.SetRestAsync(s.Live.Slug,hero.Fighter.AccountId,new(true),default);
        Assert.False(await hub.Retreat(s.Live.RunId,hero.Id));
    }

