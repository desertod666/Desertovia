    }

    [Fact]
    public async Task Recovery_preserves_gathering_march_and_bad_save_but_returns_legacy_running_heroes_home()
    {
        var s = await Setup();
        await using var db = await Contexts.CreateDbContextAsync();
        var now = factory.Clock.GetUtcNow();
        var runs = new[] { DungeonPhase.Gathering, DungeonPhase.Marching, DungeonPhase.Running, DungeonPhase.Running }
            .Select(phase => new DungeonRun
            {
                VillageId = s.Live.VillageId, DungeonId = DungeonCatalog.DeadLands, Phase = phase,
                OpenedAt = now, GatheringEndsAt = now.AddHours(1), MarchEndsAt = now.AddHours(2),
                Heroes = [new DungeonHero { AccountId = Guid.NewGuid(), Name = "Legacy tsar", Class = HeroClass.Voivode }],
            }).ToArray();
        runs[3].CheckpointJson = "{\"unsupported\":true}";
        db.DungeonRuns.AddRange(runs);
        await db.SaveChangesAsync();
        await s.Game.RestoreDungeonsAsync(default);
        db.ChangeTracker.Clear();
        var loaded = await db.DungeonRuns.Where(r => runs.Select(run => run.Id).Contains(r.Id)).ToDictionaryAsync(r => r.Id);
        Assert.Equal(DungeonPhase.Gathering, loaded[runs[0].Id].Phase);
        Assert.Equal(DungeonPhase.Marching, loaded[runs[1].Id].Phase);
        Assert.Equal(DungeonOutcome.Abandoned, loaded[runs[2].Id].Outcome);
        Assert.Equal(DungeonPhase.Running, loaded[runs[3].Id].Phase);
        Assert.True(System.Text.Json.Nodes.JsonNode.DeepEquals(
            System.Text.Json.Nodes.JsonNode.Parse(runs[3].CheckpointJson!),
            System.Text.Json.Nodes.JsonNode.Parse(loaded[runs[3].Id].CheckpointJson!)));
    }
