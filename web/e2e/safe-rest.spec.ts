import {test, expect, developmentLogin, expectVillageView, DEMO_SLUG, uniqueName} from './fixtures.ts'

test.setTimeout(120_000)
test.use({deviceScaleFactor: 1})
for (const language of ['en', 'ru']) test(`safe rest is a server choice across tabs and reload, with compact phone controls (${language})`, async ({page, context}) => {
  // Sign in/create with English labels, then change the presentation language.
  await page.addInitScript(() => localStorage.setItem('desertod.language', 'en'))
  await page.setViewportSize({width: 320, height: 760})
  await page.goto(`/v/${DEMO_SLUG}`)
  await developmentLogin(page, uniqueName('safe-rest'))
  await expectVillageView(page)
  await page.evaluate(value => localStorage.setItem('desertod.language', value), language)
  // Existing init script is English; set the desired language for subsequent navigations.
  await page.addInitScript(value => localStorage.setItem('desertod.language', value), language)
  await page.reload(); await expectVillageView(page)
  const control = page.locator('.safe-rest-control')
  await expect(control).toHaveAttribute('data-state', 'Active')
  const button = control.locator('button').first()
  expect((await button.boundingBox())!.height).toBeGreaterThanOrEqual(44)
  await button.click()
  await expect(control).toHaveAttribute('data-state', 'Resting')
  await expect(page.locator('.next-action')).toContainText(language === 'ru' ? 'Безопасный отдых' : 'Safe rest')
  expect((await page.request.post(`/api/villages/${DEMO_SLUG}/me/task`, {data: {taskId: 'chop-wood'}})).status()).toBe(400)
  const other = await context.newPage()
  await other.goto(`/v/${DEMO_SLUG}`); await expectVillageView(other)
  await expect(other.locator('.safe-rest-control')).toHaveAttribute('data-state', 'Resting')
  await page.reload(); await expectVillageView(page)
  await expect(control).toHaveAttribute('data-state', 'Resting')
  await control.locator('button').last().click()
  await expect(page.getByRole('tooltip')).toContainText(language === 'ru' ? 'один раз' : 'once')
  await page.keyboard.press('Escape')
  const box = await control.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0); expect(box!.x + box!.width).toBeLessThanOrEqual(320)
  await button.click()
  await expect(control).toHaveAttribute('data-state', 'Active')
  await expect(other.locator('.safe-rest-control')).toHaveAttribute('data-state', 'Active')
  await other.close()
})
