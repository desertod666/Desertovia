test('real map closes the hint before the wallet without opening a background menu', async ({page}) => {
  await page.addInitScript(()=>localStorage.setItem('desertod.language','ru'))
  await page.setViewportSize({width:320,height:844})
  await page.request.post('/auth/dev-login',{data:{name:uniqueName('compact-map')}})
  await page.request.post('/api/me/character',{data:{name:'Проверка интерфейса',appearance:{gender:'Female',style:0,skinTone:0,hairColor:0,outfitColor:0}}})
  await page.request.post('/api/villages/demo-bridge/citizens',{data:{inviteCode:null}})
  await page.goto('/v/demo-bridge')
  await expect(page.locator('canvas').first()).toBeVisible({timeout:60000})
  await expect(page.locator('.hud-needs')).toBeVisible()
  const guide=page.locator('.guide')
  await expect(guide).toHaveClass(/collapsed/)
  await guide.locator('.hud-card-head').click()
  await expect(guide).not.toHaveClass(/collapsed/)
  await page.reload()
  await expect(guide).not.toHaveClass(/collapsed/)
  await guide.locator('.hud-card-head').click()
  await page.locator('.wallet-hud').click()
  const wallet=page.getByRole('dialog',{name:'Кошелёк',exact:true})
  await expect(wallet).toBeVisible()
  await page.getByRole('button',{name:'О деньгах и оплате труда'}).click()
  await expect(page.getByRole('tooltip')).toBeVisible()
  expect(await page.getByRole('tooltip').evaluate(el=>el.closest('[aria-modal="true"]')!==null)).toBe(true)
  // A host can register its capture listener later when it rerenders. One Escape must not reach it.
  await page.evaluate(()=>window.addEventListener('keydown',event=>{
    if(event.key==='Escape')document.documentElement.dataset.escapedPastHint='1'
  },{capture:true,once:true}))
  await page.keyboard.press('Escape')
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await expect(page.locator('html')).not.toHaveAttribute('data-escaped-past-hint','1')
  await expect(wallet).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(wallet).toHaveCount(0)
  await expect(page.locator('.modal.menu')).toHaveCount(0)
})
