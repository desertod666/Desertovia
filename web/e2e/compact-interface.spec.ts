import { test, expect, uniqueName } from './fixtures'

for (const language of ['ru', 'en']) {
  const ru = language === 'ru'
  test(`compact needs keep phone map space and tap hints readable (${language})`, async ({ page }) => {
    await page.addInitScript(value => localStorage.setItem('desertod.language', value), language)
    await page.request.post('/auth/dev-login', {data: {name: uniqueName('compact-needs')}})
    await page.route('**/api/villages/stand/economy?*', route => route.fulfill({json: {coins: 123, testCandles: 4}}))
    for (const width of [320, 390, 960]) {
      await page.setViewportSize({width, height: 760})
      await page.goto('/e2e/post-071-harness.html?hud=1&needs=1')
      const needs = page.locator('.hud-needs')
      await expect(needs).toContainText(ru ? 'Сыт' : 'Fed')
      expect((await needs.innerText()).length).toBeLessThan(45)
      expect((await needs.boundingBox())!.height).toBeLessThan(55)
      expect(await needs.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
      const food = page.getByRole('button', {name: ru ? 'Подробности питания' : 'Food details', exact: true})
      const rest = page.getByRole('button', {name: ru ? 'Подробности восстановления сил' : 'Energy recovery details', exact: true})
      for (const control of [food, rest]) {
        if (width < 721) expect((await control.boundingBox())!.height).toBeGreaterThanOrEqual(44)
        await control.click()
        await expect(control).toHaveAttribute('aria-expanded', 'true')
        const hint = page.getByRole('tooltip')
        await expect(hint).toBeVisible()
        const box = (await hint.boundingBox())!
        expect(box.x).toBeGreaterThanOrEqual(0)
        expect(box.x + box.width).toBeLessThanOrEqual(width)
        expect(box.y).toBeGreaterThanOrEqual(0)
        expect(box.y + box.height).toBeLessThanOrEqual(760)
      }
      await expect(page.getByRole('tooltip')).toHaveCount(1)
      await expect(food).toHaveAttribute('aria-expanded', 'false')
      await expect(page.getByRole('tooltip')).toContainText('40')
      await page.keyboard.press('Escape')
      await expect(page.getByRole('tooltip')).toHaveCount(0)
      await food.focus()
      await page.keyboard.press('Enter')
      await expect(page.getByRole('tooltip')).toBeVisible()
      await page.locator('.game-root').click({position: {x: 150, y: 300}})
      await expect(page.getByRole('tooltip')).toHaveCount(0)
      if (width === 320) await page.screenshot({path: test.info().outputPath(`compact-needs-${language}.png`)})
    }
  })

  test(`wallet hides secondary copy but preserves prices and drafts (${language})`, async ({page}) => {
    await page.addInitScript(value => localStorage.setItem('desertod.language', value), language)
    await page.setViewportSize({width: 320, height: 760})
    await page.goto('/e2e/economy-harness.html')
    await page.locator('.economy-panel > summary').click()
    const help = page.getByRole('button', {name: ru ? 'О деньгах и оплате труда' : 'About money and work pay'})
    await expect(help).toBeVisible()
    await expect(page.locator('.energy-shop')).toBeHidden()
    const recipient = page.locator('.economy-transfer select')
    await expect(recipient).toBeHidden()
    const buy = page.getByRole('button', {name: ru ? /Купить у царства/ : /Buy from kingdom/})
    await expect(buy).toBeVisible()
    await expect(buy).toContainText(ru ? '2 золота' : '2 gold')
    await help.click()
    await expect(page.getByRole('tooltip')).toContainText(ru ? 'Личная стройка не оплачивается' : 'Private construction earns no kingdom wages')
    await page.locator('.modal-body').evaluate(el => {el.scrollTop = 100})
    await expect(page.getByRole('tooltip')).toHaveCount(0)
    await page.getByLabel(ru ? 'Количество' : 'Amount', {exact: true}).fill('2')
    const transfer = page.locator('.economy-transfer > summary')
    await transfer.click()
    await recipient.selectOption('other')
    await transfer.click()
    await transfer.click()
    await expect(recipient).toHaveValue('other')
    await transfer.click()
    await page.locator('.energy-shop-disclosure > summary').click()
    await expect(page.locator('.energy-shop .row')).toContainText(ru ? '300 золота' : '300 gold')
    await expect(page.locator('.energy-shop .row')).toContainText(ru ? '3 тестовые свечи' : '3 test candles')
    await page.getByRole('button', {name: ru ? 'Об энергетике' : 'About the energy drink'}).click()
    await expect(page.getByRole('tooltip')).toContainText(ru ? '12 реальных часов' : '12 real hours')
    await page.keyboard.press('Escape')
    await expect(page.locator('.economy-panel')).toBeVisible()
    await expect(page.getByLabel(ru ? 'Количество' : 'Amount', {exact: true})).toHaveValue('2')
    for (const theme of ['light', 'dark']) {
      await page.evaluate(value => {document.documentElement.dataset.uiTheme = value}, theme)
      expect(await page.locator('.economy-panel').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    }
    await page.locator('.energy-shop-disclosure > summary').click()
    await page.locator('.modal-body').evaluate(el => {el.scrollTop = 0})
    await page.locator('.modal.menu').screenshot({path: test.info().outputPath(`compact-wallet-${language}.png`)})
    expect(await page.evaluate(() => window.economyCalls)).toEqual([])
  })
}

test('hunger and tired warnings stay visible while formulas remain in tap hints', async ({page}) => {
  await page.addInitScript(() => localStorage.setItem('desertod.language', 'ru'))
  await page.request.post('/auth/dev-login', {data: {name: uniqueName('compact-hungry')}})
  await page.route('**/api/villages/stand/economy?*', route => route.fulfill({json: {coins: 123, testCandles: 4}}))
  await page.setViewportSize({width: 320, height: 760})
  await page.goto('/e2e/post-071-harness.html?hud=1&needs=1&hungry=1&tired=1')
  await expect(page.locator('.hud-needs .needs-warning')).toHaveCount(2)
  await expect(page.locator('.hud-needs')).toContainText('Голоден')
  await expect(page.locator('.hud-needs')).toContainText('Устал')
  await page.getByRole('button', {name: 'Подробности питания', exact: true}).click()
  await expect(page.getByRole('tooltip')).toContainText('опыт')
})
